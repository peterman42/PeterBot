#include "move.h"

//////////////////////////////////////////////////////////////////
Move::Move(float speed,Wheel** wheels, int numberOfWheels)
{
    setSpeed(speed);
    setWheels(wheels);
    setNumberOfWheels(numberOfWheels);
}

//////////////////////////////////////////////////////////////////
void Move::setWheels(Wheel** wheels)
{
    Move::wheels = wheels;
}

//////////////////////////////////////////////////////////////////
Wheel** Move::getWheels()
{
    return Move::wheels;
}

//////////////////////////////////////////////////////////////////
void Move::setSpeed(float speed)
{
    Move::speed = speed;
}

//////////////////////////////////////////////////////////////////
float& Move::getSpeed()
{
    return Move::speed;
}

//////////////////////////////////////////////////////////////////
void Move::setNumberOfWheels(int numberOfWheels)
{
    Move::numberOfWheels = numberOfWheels;
}
//////////////////////////////////////////////////////////////////
int& Move::getNumberOfWheels()
{
    return Move::numberOfWheels;
}

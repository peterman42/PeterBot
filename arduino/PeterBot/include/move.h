#ifndef MOVE_H
#define MOVE_H

#include "wheel.h"

class Move
{
public:

    Move() = default;
    Move(float speed, Wheel** wheels, int numberOfWheels);

    virtual ~Move()
    {
        for(int i =0; i< numberOfWheels; ++i)
            delete wheels[i];

        delete wheels;
    }

    //////////////////////////////////////////////////////////////////
	virtual void begin(int num)=0;
    //////////////////////////////////////////////////////////////////
	virtual void stop(int num) = 0;
    //////////////////////////////////////////////////////////////////
	void setWheels(Wheel** wheels);
    //////////////////////////////////////////////////////////////////
	Wheel** getWheels();
    //////////////////////////////////////////////////////////////////
	void setSpeed(float speed);
    //////////////////////////////////////////////////////////////////
	float& getSpeed();
    //////////////////////////////////////////////////////////////////
    void setNumberOfWheels(int numberOfWheels);
    //////////////////////////////////////////////////////////////////
    int& getNumberOfWheels();

	float speed;
    Wheel** wheels;
    int numberOfWheels;
};
#endif
